export function detectPlatform(message: string): string {
  const lower = message.toLowerCase();
  if (/لينكد\s*إن|linkedin/i.test(lower)) return "linkedin";
  if (/تويتر|twitter|tweet|x\s*(?!\.com)/i.test(lower)) return "twitter";
  if (/فيس|facebook/i.test(lower)) return "facebook";
  if (/انستقرام|انستا|instagram/i.test(lower)) return "instagram";
  if (/بريد|email|nurture|نيوزليتر/i.test(lower)) return "email";
  if (/بحث|research/i.test(lower)) return "research";
  if (/صفحة|landing|page|مقال|article/i.test(lower)) return "page";
  return "linkedin";
}
